"""Generate sql/02_sample_data.sql: realistic, internally consistent Berlin sample data.

The data is synthetic. It is seeded, so every run produces the same file. Rules it follows:

* Prices are area x a district price per square metre, with some spread.
* Every closed sale has a contract date after its offer date, and an offer date after
  the listing date. All dates are in the past.
* A property's status agrees with its deals: a closed deal means SOLD, an open offer
  means UNDER_OFFER, otherwise AVAILABLE (or WITHDRAWN when the owner pulled it).
* The status history shows each listing's path, as if migrated from the old spreadsheets.

Run:  python scripts/generate_sample_data.py > sql/02_sample_data.sql
"""

from __future__ import annotations

import random
from datetime import date, timedelta

rng = random.Random(2024)

STATUSES = [(1, "AVAILABLE", "Listed and open for offers"), (2, "SOLD", "Contract signed, sale closed"),
            (3, "UNDER_OFFER", "Offer accepted, contract not yet signed"), (4, "WITHDRAWN", "Taken off the market by the owner")]
TYPES = [(1, "Apartment", "RESIDENTIAL"), (2, "House", "RESIDENTIAL"), (3, "Condo", "RESIDENTIAL"),
         (4, "Office", "COMMERCIAL"), (5, "Retail Unit", "COMMERCIAL")]
# district, postal codes, price per sqm (EUR), streets in that district
DISTRICTS = [
    ("Mitte", ["10115", "10117", "10119"], 7400, ["Torstrasse", "Invalidenstrasse", "Linienstrasse", "Auguststrasse"]),
    ("Friedrichshain-Kreuzberg", ["10243", "10245", "10961"], 6600,
     ["Boxhagener Strasse", "Simon-Dach-Strasse", "Bergmannstrasse", "Oranienstrasse"]),
    ("Pankow", ["10405", "10435", "13187"], 6100,
     ["Kastanienallee", "Schoenhauser Allee", "Kollwitzstrasse", "Danziger Strasse"]),
    ("Charlottenburg-Wilmersdorf", ["10585", "10707", "14057"], 7000,
     ["Kantstrasse", "Wilmersdorfer Strasse", "Pestalozzistrasse", "Sybelstrasse"]),
    ("Neukoelln", ["12043", "12047", "12053"], 5200, ["Sonnenallee", "Karl-Marx-Strasse", "Weserstrasse", "Pannierstrasse"]),
    ("Tempelhof-Schoeneberg", ["10777", "10827", "12103"], 5800,
     ["Akazienstrasse", "Goltzstrasse", "Hauptstrasse", "Crellestrasse"]),
    ("Steglitz-Zehlendorf", ["12163", "14163", "14195"], 6300,
     ["Schlossstrasse", "Albrechtstrasse", "Clayallee", "Teltower Damm"]),
    ("Treptow-Koepenick", ["12435", "12555", "12587"], 4900,
     ["Boelschestrasse", "Bahnhofstrasse", "Gruenauer Strasse", "Puschkinallee"]),
]
AGENTS = [
    (301, "Lena", "Hoffmann", "2019-03-01", True), (302, "Jonas", "Becker", "2020-06-15", True),
    (303, "Aylin", "Demir", "2021-01-11", True), (304, "Markus", "Schulz", "2018-09-03", True),
    (305, "Sofia", "Richter", "2022-04-19", True), (306, "Tobias", "Wagner", "2023-02-06", True),
    (307, "Priya", "Nair", "2023-10-02", True), (308, "Felix", "Krause", "2017-05-22", False),
]
PEOPLE = [("Anna", "Schmidt"), ("Lukas", "Fischer"), ("Marie", "Weber"), ("Paul", "Meyer"), ("Emma", "Wolf"),
          ("Ben", "Neumann"), ("Mia", "Schwarz"), ("Noah", "Zimmermann"), ("Hannah", "Braun"), ("Elias", "Hartmann"),
          ("Lea", "Lange"), ("Finn", "Werner"), ("Clara", "Koch"), ("Leon", "Kaiser"), ("Mila", "Fuchs"),
          ("David", "Peters"), ("Sara", "Yilmaz"), ("Omar", "Haddad")]
COMPANIES = ["Spree Wohnbau GmbH", "Kiez Retail Partners GmbH", "Havel Asset Management AG", "Nordlicht Praxis GmbH"]
TODAY = date(2025, 10, 31)  # data snapshot date


def q(value: object) -> str:
    """SQL literal."""
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def rows(table: str, cols: list[str], data: list[tuple[object, ...]]) -> str:
    body = ",\n".join("    (" + ", ".join(q(v) for v in r) + ")" for r in data)
    return f"INSERT INTO {table} ({', '.join(cols)}) VALUES\n{body};\n"


def main() -> None:
    out: list[str] = []
    w = out.append
    w("-- =============================================================================\n"
      "-- Berealty Real Estate RDBMS\n"
      "-- 02_sample_data.sql : synthetic, internally consistent sample data\n"
      "--\n"
      "-- Generated by scripts/generate_sample_data.py (seeded, reproducible).\n"
      "-- Snapshot date of the data: 2025-10-31. All people and companies are fictitious.\n"
      "-- Load after 01_schema_creation.sql. Statuses below already agree with the deals,\n"
      "-- as they would after migrating the old spreadsheets; from here on the triggers in\n"
      "-- 04_triggers_and_automation.sql keep them in step.\n"
      "-- =============================================================================\n\n"
      "USE berealty;\nSET NAMES utf8mb4;\nSTART TRANSACTION;\n\n")

    w("-- Lookups\n")
    w(rows("property_status", ["status_id", "status_code", "description"], STATUSES))
    w(rows("property_type", ["property_type_id", "type_name", "segment"], TYPES))
    w(rows("district", ["district_id", "district_name"], [(i + 1, d[0]) for i, d in enumerate(DISTRICTS)]))

    w("\n-- Agents (agent 308 has left the company and can no longer take new deals)\n")
    w(rows("agent", ["agent_id", "first_name", "last_name", "email", "phone", "hire_date", "is_active"],
           [(a, f, l, f"{f.lower()}.{l.lower()}@berealty.de", f"+49 30 5550 {a}", h, act)
            for a, f, l, h, act in AGENTS]))

    clients = []
    for i, (f, l) in enumerate(PEOPLE):
        clients.append((201 + i, "INDIVIDUAL", f, l, None, f"{f.lower()}.{l.lower()}@example.com", f"+49 151 {4000000 + i * 7919}"))
    for j, c in enumerate(COMPANIES):
        slug = c.split()[0].lower()
        clients.append((201 + len(PEOPLE) + j, "COMMERCIAL", None, None, c, f"acquisitions@{slug}.example.com", f"+49 30 {7000000 + j * 4567}"))
    w("\n-- Clients: households and companies\n")
    w(rows("client", ["client_id", "client_type", "first_name", "last_name", "company_name", "email", "phone"], clients))

    # ---- properties
    props = []
    used = set()
    for pid in range(101, 133):
        d_idx = rng.randrange(len(DISTRICTS))
        name, codes, ppsqm, streets = DISTRICTS[d_idx]
        t = rng.choices([1, 2, 3, 4, 5], weights=[50, 12, 22, 9, 7])[0]
        area = {1: rng.uniform(38, 130), 2: rng.uniform(110, 240), 3: rng.uniform(55, 150),
                4: rng.uniform(120, 600), 5: rng.uniform(60, 300)}[t]
        rooms = None if t >= 4 else round(max(1.0, area / rng.uniform(25, 35)) * 2) / 2
        factor = {1: 1.0, 2: 0.85, 3: 1.05, 4: 0.75, 5: 0.8}[t]
        price = round(area * ppsqm * factor * rng.uniform(0.88, 1.15), -3)
        while True:
            addr = f"{rng.choice(streets)} {rng.randint(1, 180)}"
            code = rng.choice(codes)
            if (addr, code) not in used:
                used.add((addr, code))
                break
        listed = date(2024, 1, 8) + timedelta(days=rng.randint(0, 600))
        agent = None if pid in (129, 131) else rng.choice([301, 302, 303, 304, 305, 306, 307] + ([308] if pid < 110 else []))
        props.append({"id": pid, "addr": addr, "code": code, "district": d_idx + 1, "type": t,
                      "area": round(area, 1), "rooms": rooms, "price": price, "agent": agent, "listed": listed})

    # ---- deals: decide each property's story
    deals, history = [], []
    tid = 401
    client_pool = [c[0] for c in clients]
    repeat_buyer = 219  # Spree Wohnbau GmbH buys several units
    for p in props:
        story = rng.choices(["sold", "offer", "available", "cancel_then_sold", "withdrawn"],
                            weights=[56, 10, 18, 8, 4])[0]
        if p["id"] in (129, 131):
            story = "available"  # unassigned listings stay on the market
        if p["id"] == 130:
            story = "withdrawn"
        if p["listed"] > TODAY - timedelta(days=45) and story in ("sold", "cancel_then_sold"):
            story = "offer"
        agent = p["agent"] if p["agent"] and p["agent"] != 308 else rng.choice([301, 302, 303, 304, 305])
        status = 1
        hist = [(p["id"], None, 1, p["listed"])]
        t = p["listed"]

        def new_deal(stage: str, start: date, client: int) -> date:
            nonlocal tid
            offer = start + timedelta(days=rng.randint(10, 75))
            if stage == "OFFER":  # open offers are recent; old ones would have closed or lapsed
                offer = max(start + timedelta(days=10), TODAY - timedelta(days=rng.randint(5, 50)))
            close = offer + timedelta(days=rng.randint(21, 70)) if stage == "CLOSED" else None
            amount = round(p["price"] * rng.uniform(0.94, 1.06), -2)
            deals.append((tid, p["id"], client, agent, stage, offer, close, amount))
            tid += 1
            return close or offer

        if story == "cancel_then_sold":
            c1 = rng.choice(client_pool)
            end = new_deal("CANCELLED", t, c1)
            hist += [(p["id"], 1, 3, deals[-1][5]), (p["id"], 3, 1, end + timedelta(days=rng.randint(5, 20)))]
            t = hist[-1][3]
            story = "sold"
        if story == "sold":
            client = repeat_buyer if p["type"] in (1, 3) and rng.random() < 0.15 else rng.choice(client_pool)
            close = new_deal("CLOSED", t, client)
            if close > TODAY:  # keep all history in the past
                deals.pop()
                tid -= 1
                new_deal("OFFER", t, client)
                hist.append((p["id"], 1, 3, deals[-1][5]))
                status = 3
            else:
                hist += [(p["id"], 1, 3, deals[-1][5]), (p["id"], 3, 2, close)]
                status = 2
        elif story == "offer":
            new_deal("OFFER", t, rng.choice(client_pool))
            hist.append((p["id"], 1, 3, deals[-1][5]))
            status = 3
        elif story == "withdrawn":
            hist.append((p["id"], 1, 4, min(TODAY, t + timedelta(days=rng.randint(60, 150)))))
            status = 4
        p["status"] = status
        history += hist

    w("\n-- Properties (129 and 131 are not yet assigned to an agent)\n")
    w(rows("property", ["property_id", "street_address", "postal_code", "district_id", "property_type_id", "area_sqm",
                        "rooms", "list_price", "status_id", "listing_agent_id", "listed_date"],
           [(p["id"], p["addr"], p["code"], p["district"], p["type"], p["area"], p["rooms"], p["price"], p["status"],
             p["agent"], p["listed"].isoformat()) for p in props]))

    w("\n-- Deals. stage: OFFER (open), CLOSED (sold), CANCELLED (buyer withdrew)\n")
    w(rows("sale_transaction", ["transaction_id", "property_id", "client_id", "agent_id", "stage", "offer_date",
                                "transaction_date", "sale_amount"],
           [(d[0], d[1], d[2], d[3], d[4], d[5].isoformat(), d[6].isoformat() if d[6] else None, d[7]) for d in deals]))

    w("\n-- Status history as migrated from the spreadsheets\n")
    history.sort(key=lambda h: (h[3], h[0]))
    w(rows("property_status_history", ["property_id", "old_status_id", "new_status_id", "changed_at", "changed_by"],
           [(h[0], h[1], h[2], f"{h[3].isoformat()} 09:00:00", "migration") for h in history]))
    w("\nCOMMIT;\n")
    print("".join(out), end="")


if __name__ == "__main__":
    main()
